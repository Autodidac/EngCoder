"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const css = fs.readFileSync(path.join(root, "css/engcoder.css"), "utf8");
const ui = fs.readFileSync(path.join(root, "js/ui.js"), "utf8");
const state = fs.readFileSync(path.join(root, "js/state.js"), "utf8");
const api = fs.readFileSync(path.join(root, "js/api.js"), "utf8");
assert.match(html, /id="quickAttachmentCount"[^>]*\bhidden\b/);
assert.match(css, /\.composer-attachment-count\[hidden\]\s*\{\s*display\s*:\s*none\s*!important\s*;/);
assert.match(ui, /quickAttachmentCount\.hidden\s*=\s*count\s*===\s*0/);
assert.match(html, /id="simpleRoutingStatus"/);
assert.match(state, /Previously selected small model is unavailable/);
assert.match(html, /id="autoRouting"/);
