assert.match(api, /auto_route:\s*\$\('autoRouting'\)/);
assert.match(api, /addons_enabled:\s*addonsEnabled/);
assert.match(html, /id="quickMissions"/);
console.log("PASS: attachment visibility, small-model feedback, independent routing toggles, preserved Missions footer");
