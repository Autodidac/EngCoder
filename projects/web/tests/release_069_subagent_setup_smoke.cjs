'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root,'js/api.js'), 'utf8');
const render = fs.readFileSync(path.join(root,'js/render.js'), 'utf8');
const html = fs.readFileSync(path.join(root,'index.html'), 'utf8');
const cpp = fs.readFileSync(path.join(root, '../native/src/agent/agent_runtime.cpp'),'utf8');
const state = fs.readFileSync(path.join(root,'js/state.js'), 'utf8');
const a = source.indexOf('function freshExecutionStats()');
const b = source.indexOf('async function deleteRuntimeSession(');
assert.ok(a > 0 && b > a);
const ctx = vm.createContext({});
vm.runInContext(source.slice(a,b)+'\nthis.fresh=freshExecutionStats;this.record=recordExecutionEvent;',ctx);
const output = {executionStats:ctx.fresh()};
let seq=0;
const feed=(type,data={})=>ctx.record(output,{type,data,sequence:++seq,timestamp_ms:1000+seq});
feed('controller.decision',{model:'lmstudio://mid',model_attempted:true,model_used:false,source:'deterministic-fallback'});
assert.equal(output.executionStats.architect.model,'');
feed('addon.requested',{addon:'cpp',model:'lmstudio://tiny',mode:'small-checklist-only'});
feed('addon.completed',{addon:'cpp',model:'lmstudio://tiny',mode:'small-checklist-only'});
assert.equal(output.executionStats.modelRoles.draftUsed,'lmstudio://tiny');
assert.equal(output.executionStats.modelRoles.draftStatus,'Completed as specialist');
feed('review.requested',{model:'lmstudio://mid'});
assert.equal(output.executionStats.modelRoles.middleUsed,'');
assert.equal(output.executionStats.modelRoles.middleStatus,'Reviewing');
feed('review.failed',{model:'lmstudio://mid'});
assert.equal(output.executionStats.modelRoles.middleUsed,'');
assert.match(output.executionStats.modelRoles.middleStatus,/Failed/);
feed('review.requested',{model:'lmstudio://mid'});
feed('review.completed',{model:'lmstudio://mid'});
assert.equal(output.executionStats.modelRoles.middleUsed,'lmstudio://mid');
assert.equal(output.executionStats.modelRoles.middleStatus,'Completed');
feed('controller.model_selected',{model:'qwenflash://large',role:'keymaker-foundation'});
assert.equal(output.executionStats.modelRoles.finalRole,'keymaker-foundation');
assert.match(render,/Small preparation · completed by/);
assert.match(render,/Middle review · state/);
assert.match(cpp,/\|\| small_candidate\)\)/);
assert.match(cpp,/small-checklist-only/);
assert.match(html,/ENGCODER_MODEL_SERVER_URL/);
assert.doesNotMatch(html,/Under Session Settings, enter the LM Studio endpoint/);
assert.doesNotMatch(html,/new 100% = old 60%/);
assert.doesNotMatch(state,/saved target \(old/);
assert.match(state,/KeyMaker is unchanged/);
console.log('PASS: distinct controller/small/middle/final outcomes, specialist fallback source, native LM Studio setup and clean GPU UI');
